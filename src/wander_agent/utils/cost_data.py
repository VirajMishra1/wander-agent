def lookup_cost(city: str | None = None, country: str | None = None) -> dict | None:
    """Find cost data for a city, falling back to country then region."""
    if city:
        key = city.lower().strip()
        if key in CITY_DAILY_BUDGET_USD:
            budget, mid, luxury = CITY_DAILY_BUDGET_USD[key]
            return {
                "match_type": "city",
                "matched_name": city,
                "daily_budget_usd": budget,
                "daily_mid_usd": mid,
                "daily_luxury_usd": luxury,
            }
    if country:
        key = country.lower().strip()
        if key in COUNTRY_DAILY_BUDGET_USD:
            budget, mid, luxury = COUNTRY_DAILY_BUDGET_USD[key]
            return {
                "match_type": "country_fallback",
                "matched_name": country,
                "daily_budget_usd": budget,
                "daily_mid_usd": mid,
                "daily_luxury_usd": luxury,
            }
        region = COUNTRY_TO_REGION.get(key)
        if region and region in REGION_DAILY_BUDGET_USD:
            budget, mid, luxury = REGION_DAILY_BUDGET_USD[region]
            return {
                "match_type": "regional_estimate",
                "matched_name": f"{country} ({region})",
                "daily_budget_usd": budget,
                "daily_mid_usd": mid,
                "daily_luxury_usd": luxury,
            }
    return None
